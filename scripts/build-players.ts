/**
 * Offline step: players-seed.csv + scripts/sources/*.json -> src/data/players.json.
 * Also writes scripts/sources/report.md listing source disagreements and TODO_VERIFY items.
 */
import { existsSync, writeFileSync } from 'node:fs'
import { resolvePlayer } from './lib/resolve.ts'
import {
  CRICSHEET_PATH,
  PLAYERS_PATH,
  REPORT_PATH,
  WIKIPEDIA_PATH,
  readJson,
  readSeed,
  type CricsheetSnapshot,
  type WikipediaSnapshot,
} from './lib/sources.ts'
import type { Player } from '../src/types.ts'

const seed = readSeed()
const wiki = readJson<WikipediaSnapshot>(WIKIPEDIA_PATH)
const cricsheet: CricsheetSnapshot | null = existsSync(CRICSHEET_PATH)
  ? readJson<CricsheetSnapshot>(CRICSHEET_PATH)
  : null
const asOf = cricsheet?.latestMatch ?? wiki.fetchedAt

const players: Player[] = []
const errorLines: string[] = []
const noteLines: string[] = []

for (const row of seed) {
  const { player, errors, notes } = resolvePlayer(
    row,
    wiki.pages[row.id],
    cricsheet?.players[row.id],
    asOf,
  )
  for (const e of errors) errorLines.push(`- **${row.id}**: ${e}`)
  for (const n of notes) noteLines.push(`- **${row.id}**: ${n}`)
  if (player) players.push(player)
}

players.sort((a, b) => a.name.localeCompare(b.name))
writeFileSync(PLAYERS_PATH, JSON.stringify(players, null, 2) + '\n')

const report = [
  '# Player data build report',
  '',
  `Generated by \`scripts/build-players.ts\`. Do not edit by hand.`,
  '',
  `- Wikipedia snapshot: ${wiki.fetchedAt}`,
  `- Cricsheet snapshot: ${cricsheet ? `${cricsheet.fetchedAt} (latest match ${cricsheet.latestMatch})` : 'none'}`,
  `- Players built: ${players.length} of ${seed.length}`,
  '',
  '## How values are chosen',
  '',
  '- Country, role, batting hand, bowling type: the Wikipedia infobox, mapped to the game enums,',
  '  unless the seed CSV overrides them.',
  '- Debut year: earliest Test/ODI/T20I debut year in the infobox.',
  '- International matches: the larger of the infobox totals and the Cricsheet count. Infobox',
  '  stats can lag; Cricsheet only misses matches (it holds no men’s matches involving',
  '  Afghanistan and has gaps before 2006).',
  '- Active: the infobox international span ends in "present".',
  '',
  `## Errors (${errorLines.length})`,
  '',
  ...(errorLines.length ? errorLines : ['None.']),
  '',
  `## Notes (${noteLines.length})`,
  '',
  ...(noteLines.length ? noteLines : ['None.']),
  '',
].join('\n')
writeFileSync(REPORT_PATH, report)

console.log(`Built ${players.length}/${seed.length} players -> src/data/players.json`)
console.log(
  `Report: ${noteLines.length} note(s), ${errorLines.length} error(s) -> scripts/sources/report.md`,
)
if (errorLines.length > 0) {
  console.error(errorLines.join('\n'))
  process.exit(1)
}
